/// Builds one positive and one adjacent-directory negative sample for every
/// declared pattern. Additional samples document sensitive neighbours such as
/// credentials or virtual environments that must stay outside the rule.
RuleAudit _multiPathAudit({
  required String scope,
  required String scopeEn,
  required String boundary,
  required String boundaryEn,
  required List<String> patterns,
  String positiveRelativePath = 'broom-audit/cache.bin',
  List<RuleAuditSample> extraSamples = const [],
}) {
  final samples = <RuleAuditSample>[];
  for (var index = 0; index < patterns.length; index++) {
    final pattern = patterns[index];
    final concrete = pattern.replaceAll('*', 'broom-audit-profile');
    samples.add(
      _hit(pattern, '$concrete/broom-audit-$index/$positiveRelativePath'),
    );
    samples.add(
      _miss(
        pattern,
        '$concrete-extra/broom-audit-$index/$positiveRelativePath',
        '相邻目录不能被前缀匹配误收',
      ),
    );
  }
  samples.addAll(extraSamples);
  return _audit(
    scope: scope,
    scopeEn: scopeEn,
    boundary: boundary,
    boundaryEn: boundaryEn,
    samples: samples,
  );
}

RuleAuditSample _hit(String pattern, String path) {
  return RuleAuditSample(pattern: pattern, path: path, inScope: true);
}

RuleAuditSample _miss(
  String pattern,
  String path,
  String reason, {
  Duration age = const Duration(days: 30),
}) {
  return RuleAuditSample(
    pattern: pattern,
    path: path,
    inScope: false,
    age: age,
    reason: reason,
  );
}
